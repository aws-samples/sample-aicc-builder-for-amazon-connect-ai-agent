def package_assets_impl(
    session_id: str,
    project_name: str = "aicc-poc",
    include_readme: bool = True,
    asset_type_filter: Optional[str] = None,
) -> dict:
    """
    Package all generated assets from S3 into a ZIP file and upload to S3.

    This tool collects all assets that were generated by Sub-Agents during the session,
    packages them into a downloadable ZIP file with proper folder structure,
    uploads to S3, and returns a presigned URL for download.

    The ZIP structure follows the workshop guide conventions:
    - cloudformation/infrastructure.yaml - Complete CloudFormation template
    - lambda/{operation_id}/index.py - Lambda handler code (reference/modify)
    - openapi/openapi.yaml - OpenAPI specification
    - prompts/ai_agent_prompt.yaml - AI agent prompt
    - contact-flow/contact_flow.json - Contact flow
    - knowledge-base/{category}/*.txt - FAQ documents (optional)

    Args:
        session_id: Unique session identifier (used for S3 key)
        project_name: Name for the project folder in the ZIP
        include_readme: Include README with deployment instructions

    Returns:
        - download_url: Presigned S3 URL (valid for 24 hours)
        - expires_at: URL expiration timestamp
        - file_list: List of files included in the ZIP
        - total_size_bytes: Total size of the ZIP file
        - assets_found: Summary of what was found per asset type
    """
    bucket_name = get_bucket_name()
    if not bucket_name:
        # Try alternate environment variable
        bucket_name = os.environ.get("ASSETS_BUCKET")

    if not bucket_name:
        return {
            "success": False,
            "error": "ASSETS_BUCKET or ASSETS_BUCKET_NAME environment variable not configured"
        }

    try:
        # Package directly from S3, bypassing the NFS fast-path. The mount
        # (mountpoint-s3) caches directory metadata and recently-read object
        # content for several seconds; during an active edit session that
        # cache can shadow writes that have already been committed to S3,
        # causing the ZIP to contain first-generation content even though S3
        # versioning and the live preview show the new content. The NFS
        # fast-path is correct for agent-in-loop reads that tolerate the
        # cache window, but download handoff must read through S3.
        s3_keys = list_session_assets(session_id, s3_only=True)
        if not s3_keys:
            return {
                "success": False,
                "error": "No assets found for this session. Generate some assets first using the AI builder.",
                "session_id": session_id
            }
        parsed_assets = _parse_s3_keys(s3_keys)

        # Optional filter by asset type (matches raw type or its mapped folder name)
        if asset_type_filter:
            needle = asset_type_filter.lower()
            target_folder = ASSET_TYPE_FOLDER_MAP.get(needle, needle)
            if needle in ACXD_DOWNLOAD_ALIASES:
                # The whole ACXD application (flows, slot types, data requests, …).
                parsed_assets = {
                    k: v for k, v in parsed_assets.items()
                    if v["asset_type"].lower() in ACXD_STORAGE_TYPES
                }
            else:
                parsed_assets = {
                    k: v for k, v in parsed_assets.items()
                    if v["asset_type"].lower() == needle
                    or ASSET_TYPE_FOLDER_MAP.get(v["asset_type"].lower(), v["asset_type"].lower()) == target_folder
                }
            if not parsed_assets:
                return {
                    "success": False,
                    "error": f"No assets found for type '{asset_type_filter}'.",
                    "session_id": session_id,
                }

        logger.info(
            f"[packager] Packaging session {session_id} from S3 "
            f"({len(s3_keys)} keys, {len(parsed_assets)} parsed)"
        )

        acxd_plan = None
        if not asset_type_filter and _is_acxd_target(session_id):
            try:
                acxd_bundle, acxd_manifest, acxd_problems = _prepare_acxd_package(
                    session_id, project_name)
            except Exception:
                logger.exception("[packager] unable to prepare ACXD package")
                return {
                    "success": False,
                    "error": "ACXD packaging refused: the D9/manifest validation could not run; "
                             "see the server log for details.",
                    "session_id": session_id,
                }
            if acxd_problems:
                return {
                    "success": False,
                    "error": "ACXD packaging refused:\n- " + "\n- ".join(acxd_problems),
                    "problems": acxd_problems,
                    "session_id": session_id,
                }
            acxd_plan = (acxd_bundle, acxd_manifest)

        # Create in-memory ZIP file
        zip_buffer = io.BytesIO()
        file_list = []
        assets_found = {}

        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
            zip_paths: set[str] = set()
            # archive path → sha256 of what was written there. The preview
            # stream saves some documents twice (`<type>/<file>` and
            # `<type>/<id>/<file>`, live: research/research.json); an identical
            # second copy is the same file and is skipped — only a DIFFERENT
            # document at the same path makes the bundle ambiguous.
            zip_digests: dict[str, str] = {}
            for s3_key, asset_info in parsed_assets.items():
                asset_type = asset_info["asset_type"]
                operation_id = asset_info.get("operation_id")
                file_name = asset_info["file_name"]

                # Target-specific assets are written below from load_acxd_bundle;
                # prompts are intentionally absent for the ACXD runtime target.
                if acxd_plan and (asset_type.lower() in ACXD_STORAGE_TYPES
                                  or asset_type.lower() in {"prompt", "contact_flow", "contactflow", "contact-flow"}):
                    continue

                content = get_asset_from_s3(s3_key, s3_only=True)
                if not content:
                    logger.warning(f"[packager] empty/unreadable S3 asset: {s3_key}")
                    continue

                # ACXD delivers built-in slot values without separators (live:
                # 010-1111-2222 → 01011112222); the handler validates the spec
                # format. Wrap every ACXD bundle's Python handler so the
                # OperationSpec formats are restored before validation.
                if acxd_plan and asset_type.lower() == "lambda" and file_name.endswith(".py") \
                        and operation_id:
                    patterns = _acxd_field_patterns(operation_id)
                    # The interview often records the format only on the flow's
                    # slot (appointmentDate ^\d{4}-\d{2}-\d{2}$) and not on the
                    # OperationSpec field: the payload mapping says which slot
                    # feeds which request field.
                    for name, pattern in _acxd_slot_patterns(acxd_plan[0], operation_id).items():
                        patterns.setdefault(name, pattern)
                    try:
                        from tools.acxd_lambda_adapter import inject as _inject_adapter
                        new_content, restored = _inject_adapter(
                            content if isinstance(content, str) else content.decode("utf-8"), patterns,
                            response_types=_acxd_response_types(acxd_plan[0], operation_id))
                        if restored:
                            content = new_content
                            logger.info(f"[packager] {operation_id}: ACXD boundary adapter added ({restored})")
                    except Exception as exc:  # pragma: no cover - never block packaging on the aid
                        logger.warning(f"[packager] {operation_id}: ACXD boundary adapter skipped: {exc}")

                if asset_type.lower() in ACXD_STORAGE_TYPES:
                    # Filtered ACXD download: keep the deployment layout so the
                    # folder can be dropped into a bundle as-is.
                    zip_path = _acxd_asset_zip_path(project_name, asset_type, file_name)
                else:
                    zip_path = _get_zip_path(
                        project_name=project_name,
                        asset_type=asset_type,
                        file_name=file_name,
                        operation_id=operation_id
                    )

                if zip_path:
                    digest = hashlib.sha256(
                        content if isinstance(content, bytes) else str(content).encode("utf-8")).hexdigest()
                    if zip_path in zip_paths:
                        if zip_digests.get(zip_path) == digest:
                            logger.info(f"[packager] identical duplicate copy skipped: {s3_key} -> {zip_path}")
                            continue
                        if acxd_plan:
                            _refuse(
                                f"duplicate archive path {zip_path!r} with different content "
                                f"({s3_key}); refusing an ambiguous ACXD bundle")
                    zf.writestr(zip_path, content)
                    zip_paths.add(zip_path)
                    zip_digests[zip_path] = digest
                    file_list.append(zip_path)

                    if asset_type not in assets_found:
                        assets_found[asset_type] = []
                    assets_found[asset_type].append(file_name)

            if acxd_plan:
                acxd_bundle, acxd_manifest = acxd_plan
                for relative_path, payload, executable in build_acxd_zip_entries(
                        project_name, acxd_bundle, acxd_manifest):
                    zip_path = f"{project_name}/{relative_path}"
                    if zip_path in zip_paths:
                        _refuse(
                            f"duplicate archive path {zip_path!r}; refusing an ambiguous ACXD bundle")
                    zf.writestr(zip_path, payload)
                    if executable:
                        zf.getinfo(zip_path).external_attr = 0o755 << 16
                    zip_paths.add(zip_path)
                    file_list.append(zip_path)

                backend_problems = _manifest_file_problems(
                    acxd_manifest,
                    {item[len(project_name) + 1:] for item in zip_paths
                     if item.startswith(f"{project_name}/")},
                )
                if backend_problems:
                    _refuse(
                        "ACXD bundle is missing manifest-referenced backend assets:\n  - "
                        + "\n  - ".join(backend_problems))

            # Add README with deployment instructions
            if include_readme and file_list:
                readme_content = _generate_readme(
                    project_name=project_name,
                    assets_found=assets_found
                )
                if acxd_plan:
                    readme_content += "\n\n" + _generate_acxd_readme_section() + "\n"
                readme_path = f"{project_name}/README.md"
                zf.writestr(readme_path, readme_content)
                zip_paths.add(readme_path)
                file_list.append(readme_path)

            # Add deploy.sh for CloudShell one-click deployment (from template)
            if file_list:
                template_path = os.path.join(
                    os.path.dirname(__file__), "..", "templates", "deploy_workshop.sh"
                )
                if os.path.exists(template_path):
                    with open(template_path, "r") as f:
                        deploy_script = f.read()
                else:
                    deploy_script = None
                if deploy_script:
                    deploy_path = f"{project_name}/deploy.sh"
                    zf.writestr(deploy_path, deploy_script,
                                compress_type=zipfile.ZIP_DEFLATED)
                    # Set executable permission via external_attr
                    info = zf.getinfo(deploy_path)
                    info.external_attr = 0o755 << 16
                    zip_paths.add(deploy_path)
                    file_list.append(deploy_path)

            if acxd_plan:
                wiring_path = f"{project_name}/WIRING-GUIDE.md"
                zf.writestr(wiring_path, _generate_wiring_guide(acxd_plan[0]))
                zip_paths.add(wiring_path)
                file_list.append(wiring_path)

        # Check if we actually packaged anything
        if not file_list:
            return {
                "success": False,
                "error": "No valid assets could be retrieved from S3.",
                "session_id": session_id,
                "s3_keys_found": len(s3_keys)
            }

        # Get ZIP size
        zip_buffer.seek(0, 2)  # Seek to end
        total_size = zip_buffer.tell()
        zip_buffer.seek(0)  # Reset to beginning

        # Upload to S3 (include filter/type in key so types don't overwrite each other)
        # The DOWNLOAD filename also carries the timestamp so successive downloads
        # are distinguishable on disk (previously every download landed as the
        # same `{project_name}.zip`, which is not scalable across iterations).
        timestamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
        type_tag = f"-{asset_type_filter}" if asset_type_filter else ""
        # Sanitize project_name for use in a filename (spaces/slashes → hyphen).
        safe_project = re.sub(r'[^A-Za-z0-9._-]+', '-', (project_name or "aicc-poc")).strip('-') or "aicc-poc"
        s3_key = f"packages/{session_id}/{safe_project}{type_tag}-{timestamp}.zip"
        download_filename = f"{safe_project}{type_tag}-{timestamp}.zip"

        s3_client = get_s3_client()
        s3_client.upload_fileobj(
            zip_buffer,
            bucket_name,
            s3_key,
            ExtraArgs={
                "ContentType": "application/zip",
                "Metadata": {
                    "session-id": session_id,
                    "project-name": project_name,
                    "created-at": datetime.now(timezone.utc).isoformat(),
                    "file-count": str(len(file_list))
                }
            }
        )

        # Generate presigned URL
        presigned_url = s3_client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": bucket_name,
                "Key": s3_key,
                'ResponseContentDisposition': f'attachment; filename="{download_filename}"'
            },
            ExpiresIn=DEFAULT_EXPIRATION_SECONDS
        )

        expires_at = datetime.now(timezone.utc).timestamp() + DEFAULT_EXPIRATION_SECONDS
        expires_at_iso = datetime.fromtimestamp(expires_at, tz=timezone.utc).isoformat()

        return {
            "success": True,
            "download_url": presigned_url,
            "expires_at": expires_at_iso,
            "expires_in_hours": 24,
            "file_list": file_list,
            "file_count": len(file_list),
            "total_size_bytes": total_size,
            "total_size_mb": round(total_size / (1024 * 1024), 2),
            "s3_key": s3_key,
            "assets_found": assets_found,
            "runtime_target": "acxd" if acxd_plan else "classic",
            "message": f"Assets packaged successfully! {len(file_list)} files, {round(total_size / 1024, 1)} KB"
        }

    except ACXDPackagingError:
        # A refusal this module raised on purpose; its wording was recorded for the user.
        return {"success": False, "error": _LAST_REFUSAL.get() or "ACXD packaging refused."}
    except ClientError:
        logger.exception("[packager] S3 operation failed")
        return {
            "success": False,
            "error": "S3 operation failed; see the server log for details."
        }
    except Exception:
        logger.exception("[packager] failed to package assets")
        return {
            "success": False,
            "error": "Failed to package assets; see the server log for details."
        }


def _parse_s3_keys(s3_keys: list) -> dict:
    """
    Parse S3 keys to extract asset information.

    S3 key format: assets/{session_id}/{asset_type}/{operation_id}/{file_name}
                   or assets/{session_id}/{asset_type}/{file_name}

    Args:
        s3_keys: List of S3 key paths

    Returns:
        Dictionary mapping S3 key to asset info
    """
    parsed = {}

    for key in s3_keys:
        parts = key.split("/")

        # Expected: assets/session_id/asset_type/[operation_id/]file_name
        if len(parts) < 4 or parts[0] != "assets":
            continue

        # Extract components
        # parts[0] = "assets"
        # parts[1] = session_id
        # parts[2] = asset_type
        # parts[3] = operation_id or file_name
        # parts[4] = file_name (if operation_id present)

        asset_type = parts[2]

        if len(parts) == 4:
            # No operation_id: assets/session/type/filename
            operation_id = None
            file_name = parts[3]
        elif len(parts) == 5:
            # With operation_id: assets/session/type/op_id/filename
            operation_id = parts[3]
            file_name = parts[4]
        else:
            # Nested structure for FAQ categories: assets/session/faq/category/filename
            operation_id = parts[3]  # Category name
            file_name = parts[-1]

        parsed[key] = {
            "asset_type": asset_type,
            "operation_id": operation_id,
            "file_name": file_name
        }

    return parsed


def _get_zip_path(
    project_name: str,
    asset_type: str,
    file_name: str,
    operation_id: Optional[str] = None
) -> Optional[str]:
    """
    Determine the ZIP path for an asset.

    Args:
        project_name: Project name for the root folder
        asset_type: Type of asset
        file_name: Name of the file
        operation_id: Optional operation identifier

    Returns:
        ZIP path or None if asset type is unknown
    """
    # Get folder from mapping
    folder = ASSET_TYPE_FOLDER_MAP.get(asset_type.lower())

    if not folder:
        # Unknown asset type, try to use it as-is
        folder = asset_type.lower()

    # Build path based on asset type
    if asset_type.lower() in ("lambda",):
        # Lambda functions need operation_id subfolder
        if operation_id:
            return f"{project_name}/{folder}/{operation_id}/{file_name}"
        else:
            return f"{project_name}/{folder}/{file_name}"

    elif asset_type.lower() in ("faq", "knowledge_base", "knowledge-base"):
        # Knowledge base files use category (operation_id) as subfolder
        if operation_id:
            return f"{project_name}/{folder}/{operation_id}/{file_name}"
        else:
            return f"{project_name}/{folder}/{file_name}"

    elif asset_type.lower() == "prompt":
        # Normalize prompt filename to ai_agent_prompt.yaml for workshop consistency
        return f"{project_name}/{folder}/ai_agent_prompt.yaml"

    else:
        # Other asset types go directly into their folder
        return f"{project_name}/{folder}/{file_name}"


